def _extract_import_aliases(
    tree: "tree_sitter.Tree",
    source: bytes,
) -> dict[str, str]:
    """Extract import aliases for disambiguation.

    In D:
        import math = std.math; -> math maps to std.math

    Returns a dict mapping alias names to module paths.
    """
    aliases: dict[str, str] = {}

    for node in iter_tree(tree.root_node):
        if node.type != "import_declaration":
            continue

        # Find imported node containing alias = module_fqn
        imported = find_child_by_type(node, "imported")
        if not imported:  # pragma: no cover - defensive
            continue

        # Check if there's an alias (identifier before =)
        alias_name = None
        module_path = None

        for child in imported.children:
            if child.type == "identifier":
                alias_name = node_text(child, source)
            elif child.type == "module_fqn":
                module_path = node_text(child, source)

        if alias_name and module_path:
            aliases[alias_name] = module_path

    return aliases


def _extract_imported_modules(
    tree: "tree_sitter.Tree",
    source: bytes,
) -> list[str]:
    """Extract all imported module paths for import-scope disambiguation.

    In D, ``import errors;`` makes all public symbols from the ``errors``
    module available in the current scope.  When resolving a bare call
    like ``error()``, we prefer symbols from imported modules over
    identically-named symbols in unrelated files.

    Returns a list of module path strings converted to file-path style
    (dots replaced with ``/``), e.g. ``["errors", "dmd/errors"]``.
    """
    modules: list[str] = []

    for node in iter_tree(tree.root_node):
        if node.type != "import_declaration":
            continue

        imported = find_child_by_type(node, "imported")
        if not imported:  # pragma: no cover - defensive
            continue

        fqn = find_child_by_type(imported, "module_fqn")
        if not fqn:
            continue  # pragma: no cover - defensive

        module_name = node_text(fqn, source)
        # Convert D module path (dots) to file path (slashes)
        # e.g., "dmd.errors" -> "dmd/errors"
        modules.append(module_name.replace(".", "/"))

    return modules


def _process_import_declaration(
    source: bytes,
    file_stable_id: str,
    run_id: str,
    node: "tree_sitter.Node",
    module_registry: dict[str, str] | None = None,
) -> list[Edge]:
    """Process an import declaration.

    When *module_registry* maps module names to their symbol IDs, the
    dst of the import edge is resolved to the actual module symbol.
    Otherwise, the dst is the well-formed external-module id
    ``d:{module}:0-0:module:module`` (module in the path slot, INV-fihur)
    used for external / standard-library imports.
    """
    edges: list[Edge] = []

    imported = find_child_by_type(node, "imported")
    if not imported:
        return edges  # pragma: no cover - defensive

    fqn = find_child_by_type(imported, "module_fqn")
    if not fqn:
        return edges  # pragma: no cover - defensive

    import_name = node_text(fqn, source)

    # Resolve to actual module symbol if available
    if module_registry and import_name in module_registry:
        dst = module_registry[import_name]
        confidence = 0.95
    else:
        dst = f"d:{import_name}:0-0:module:module"
        confidence = 0.9

    edges.append(
        Edge.create(
            src=file_stable_id,
            dst=dst,
            edge_type="imports",
            line=node.start_point[0] + 1,
            confidence=confidence,
            origin=PASS_ID,
            origin_run_id=run_id,
        )
    )
    return edges


def _find_enclosing_function_d(
    node: "tree_sitter.Node",
    source: bytes,
    local_symbols: dict[str, Symbol],
) -> Optional[Symbol]:
    """Find the enclosing function Symbol by walking up parents.

    For methods inside structs/classes/interfaces, the local_symbols map
    uses qualified names (e.g., ``Searcher.search``), so we build the
    qualified name when the enclosing function is inside a container.
    """
    current = node.parent
    while current is not None:
        if current.type == "function_declaration":
            name_node = find_child_by_type(current, "identifier")
            if name_node:
                name = node_text(name_node, source)
                # Try bare name first (top-level function)
                sym = local_symbols.get(name)
                if sym:
                    return sym
                # Try qualified name (method inside container)
                parent_name = _find_parent_container(current, source)
                if parent_name:
                    sym = local_symbols.get(f"{parent_name}.{name}")
                    if sym:
                        return sym
        current = current.parent
    return None  # pragma: no cover - defensive


def _get_call_target_name_d(
    node: "tree_sitter.Node", source: bytes
) -> tuple[Optional[str], Optional[str]]:
    """Extract the target name and receiver from a call_expression.

    Handles three call patterns in D:
    1. ``writeln("hello")`` -> identifier child -> (writeln, None)
    2. ``errors.error("bad")`` -> type > identifier, '.', identifier -> (error, errors)
    3. ``to!string(42)`` -> type > template_instance > identifier -> (to, None)

    Returns (target_name, receiver) where receiver is the module prefix
    for qualified calls like math.sin().
    """
    for child in node.children:
        if child.type == "identifier":
            return (node_text(child, source), None)
        elif child.type == "type":
            # Check for template_instance first: to!string(42)
            for subchild in child.children:
                if subchild.type == "template_instance":
                    tmpl_name = find_child_by_type(subchild, "identifier")
                    if tmpl_name:
                        return (node_text(tmpl_name, source), None)
            # Qualified call like math.sin()
            # type has: identifier (math), '.', identifier (sin)
            parts = []
            for subchild in child.children:
                if subchild.type == "identifier":
                    parts.append(node_text(subchild, source))
            if len(parts) >= 2:
                return (parts[-1], parts[0])
            elif len(parts) == 1:  # pragma: no cover - defensive
                return (parts[0], None)
    return (None, None)  # pragma: no cover - defensive


def _get_ufcs_template_name(
    node: "tree_sitter.Node", source: bytes
) -> Optional[str]:
    """Extract the template function name from a UFCS property_expression.

    Handles patterns like ``arr.map!(a => a * 2)`` where the tree-sitter AST
    produces a ``property_expression`` with a ``template_instance`` child.

    Returns the function name (e.g., "map") or None if not a UFCS template.
    """
    for child in node.children:
        if child.type == "template_instance":
            tmpl_name = find_child_by_type(child, "identifier")
            if tmpl_name:
                return node_text(tmpl_name, source)
    return None


def _param_name_and_type(
    param_node: "tree_sitter.Node", source: bytes,
) -> tuple[Optional[str], Optional[str]]:
    """Return ``(param_name, base_type_name)`` for a D ``parameter`` node.

    A D ``parameter`` child has a ``type`` node (whose ``identifier`` is the
    type name, e.g. ``File``) followed by an ``identifier`` (the parameter
    name). ``base_type_name`` is ``None`` for an untyped / ``auto`` parameter
    so the caller records the name without a resolvable receiver type.
    """
    name: Optional[str] = None
    type_name: Optional[str] = None
    for child in param_node.children:
        if child.type == "identifier" and name is None:
            name = node_text(child, source)
        elif child.type == "type":
            tid = find_child_by_type(child, "identifier")
            if tid is not None:
                type_name = node_text(tid, source)
    return name, type_name


def _first_param_type(
    func_node: "tree_sitter.Node", source: bytes,
) -> Optional[str]:
    """Base type of a D function's FIRST parameter (its UFCS receiver type).

    ``bool exists(File f)`` → ``"File"``; a UFCS call ``x.exists()`` where ``x``
    has type ``File`` is sugar for ``exists(x)``, so the receiver-type-index
    linker (INV-vigaf) matches the call's ``receiver_type_hint`` against this.
    """
    params = find_child_by_type(func_node, "parameters")
    if params is None:  # pragma: no cover - function_declaration always has ()
        return None
    for child in params.children:
        if child.type == "parameter":
            _name, type_name = _param_name_and_type(child, source)
            return type_name
    return None


def _extract_param_var_types(
    func_node: "tree_sitter.Node", source: bytes,
) -> dict[str, Optional[str]]:
    """Map each parameter name to its base type (``None`` when untyped).

    WI-situj: the receiver of a UFCS call (``thing.exists()``) is most often a
    function parameter. Tracking parameter types lets the call site emit a
    ``receiver_type_hint`` (typed) or an un-hinted unresolved edge (auto),
    either way withholding the misbinding bare-name resolution. Local variable
    declarations and ``auto`` locals are a documented residual — not tracked
    here.
    """
    result: dict[str, Optional[str]] = {}
    params = find_child_by_type(func_node, "parameters")
    if params is None:  # pragma: no cover - function_declaration always has ()
        return result
    for child in params.children:
        if child.type == "parameter":
            name, type_name = _param_name_and_type(child, source)
            if name:
                result[name] = type_name
    return result


def _enclosing_function_node(
    node: "tree_sitter.Node",
) -> Optional["tree_sitter.Node"]:
    """Walk parents to the enclosing ``function_declaration`` node, or None."""
    current = node.parent
    while current is not None:
        if current.type == "function_declaration":
            return current
        current = current.parent
    return None


def _is_module_receiver(
    receiver: str,
    import_aliases: dict[str, str],
    imported_modules: list[str],
) -> bool:
    """Is a D call prefix ``P`` in ``P.name()`` a MODULE, or a VALUE (UFCS)?

    ``P`` is a module-qualified call (resolve normally) when it is an import alias
    or (the last segment of) an imported module path. Otherwise ``P`` is a value
    expression — a parameter, local, loop variable, or field — and ``P.name()`` is
    UFCS sugar for ``name(P)``; a bare short-name resolution of ``name`` would
    misbind to an arbitrary same-named internal free function (INV-fahub, the
    real-repro ``exists``/``startsWith``/``toString`` funnel on dub), so the caller
    withholds it and lets the ``receiver_type_dispatch`` linker (INV-vigaf) recover
    it from a ``receiver_type_hint`` when the value's type is known.
    """
    if receiver in import_aliases:
        return True
    for module in imported_modules:
        if module == receiver or module.rsplit(".", 1)[-1] == receiver:
            return True
    return False


def _resolve_and_emit_call_edge(
    caller: Symbol,
    target_name: str,
    receiver: Optional[str],
    import_aliases: dict[str, str],
    imported_modules: list[str],
    resolver: NameResolver,
    edges: list[Edge],
    node: "tree_sitter.Node",
    run_id: str,
    var_types: Optional[dict[str, Optional[str]]] = None,
) -> None:
    """Resolve a call target and emit a call edge.

    Shared between regular call_expression and UFCS property_expression
    handling. Uses import aliases for qualified calls and import-scope
    path_hints for bare calls to disambiguate cross-file resolution.
    """
    # WI-situj (INV-fahub / INV-vigaf): UFCS receiver gate. When the receiver is
    # a VALUE expression (any prefix that is not an imported module) — a
    # parameter, local, loop variable, or field — ``thing.exists()`` is NOT a
    # module-qualified call; it is UFCS sugar for ``exists(thing)``. The bare
    # ``resolver.lookup`` below would misbind it to an arbitrary same-named free
    # function ``exists()`` at 0.85 (real-repro dub funnel: ``startsWith`` /
    # ``toString`` / ``exists`` on locals & loop vars, not just parameters).
    # Instead emit the call unresolved with a ``receiver_type_hint`` when the
    # value's type is known (a typed parameter) and let the
    # ``receiver_type_dispatch`` linker recover the UFCS free function by matching
    # its first-parameter type; an untyped local / ``auto`` / builtin receiver
    # still withholds the misbind — the call stays honestly external.
    if receiver is not None and not _is_module_receiver(
        receiver, import_aliases, imported_modules,
    ):
        hint = var_types.get(receiver) if var_types else None
        edges.append(make_unresolved_edge(
            "d", caller.id, target_name,
            node.start_point[0] + 1, PASS_ID, run_id,
            receiver_type_hint=hint,
        ))
        return

    # Get path hint from import aliases if receiver is aliased
    path_hint: Optional[str] = None
    if receiver:
        path_hint = import_aliases.get(receiver)

    # Use resolver for callee resolution.  For bare calls
    # (no receiver), pass imported module paths as hints
    # so the resolver prefers symbols from imported modules
    # over identically-named symbols in unrelated files.
    hints = imported_modules if not receiver else None
    lookup_result = resolver.lookup(
        target_name,
        path_hint=path_hint,
        path_hints=hints,
    )
    if lookup_result.found and lookup_result.symbol:
        edges.append(Edge.create(
            src=caller.id,
            dst=lookup_result.symbol.id,
            edge_type="calls",
            line=node.start_point[0] + 1,
            confidence=0.85 * lookup_result.confidence,
            origin=PASS_ID,
            origin_run_id=run_id,
        ))
    else:
        # External function (e.g., writeln from std.stdio)
        edges.append(make_unresolved_edge(
            "d", caller.id, target_name,
            node.start_point[0] + 1,
            PASS_ID, run_id,
        ))


