PASS_ID = make_pass_id("d")


def find_d_files(repo_root: Path) -> Iterator[Path]:
    """Find all D language files in the repository.

    Filters out GCC Makefile dependency files (``.d`` generated by
    ``gcc -MMD``) using content-based classification.  ``.di`` files
    (D interface files) are always included without classification.
    """
    for path in find_files(repo_root, ["*.d", "*.di"]):
        if classify_dot_d_file(path) == "d":
            yield path


