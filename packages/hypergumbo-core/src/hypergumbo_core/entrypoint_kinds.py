def _is_kind_attr(node: ast.AST) -> Optional[str]:
    """``EntrypointKind.X`` or ``EntrypointKind.X.value`` -> ``X``."""
    if isinstance(node, ast.Attribute) and node.attr == "value":
        node = node.value
    if (isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name)
            and node.value.id == "EntrypointKind"):
        return node.attr
    return None


def _kind_members(node: ast.AST, values: frozenset[str]) -> Optional[list[str]]:
    """The kinds a collection literal enumerates, or ``None`` if it is not one.

    A set / frozenset / tuple / list literal (or a dict's keys) counts when it
    names two or more ``EntrypointKind`` members, or when EVERY element is a
    string literal that is a kind value and there are two or more (the
    all-or-nothing rule of ``axis_drift``: a list of HTML tags that happens to
    hold "form" is not a kind set).
    """
    if isinstance(node, (ast.Set, ast.Tuple, ast.List)):
        elts = list(node.elts)
    elif isinstance(node, ast.Dict):
        elts = [k for k in node.keys if k is not None]
    else:
        return None
    attrs = [a for a in (_is_kind_attr(e) for e in elts) if a is not None]
    if len(attrs) >= 2:
        return attrs
    strings = [e.value for e in elts
               if isinstance(e, ast.Constant) and isinstance(e.value, str)]
    if len(elts) >= 2 and len(strings) == len(elts) and all(s in values for s in strings):
        return strings
    return None


def _owner_names(tree: ast.Module) -> dict[int, str]:
    """Map each node id to its enclosing function or assignment-target name."""
    owner: dict[int, str] = {}

    def visit(node: ast.AST, name: str) -> None:
        for child in ast.iter_child_nodes(node):
            child_name = name
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                child_name = child.name
            elif isinstance(child, ast.Assign) and name == "<module>":
                target = child.targets[0]
                child_name = target.id if isinstance(target, ast.Name) else name
            elif (isinstance(child, ast.AnnAssign) and name == "<module>"
                    and isinstance(child.target, ast.Name)):
                child_name = child.target.id
            owner[id(child)] = child_name
            visit(child, child_name)

    visit(tree, "<module>")
    return owner


def find_kind_set_drift_in_source(
    source: str, label: str,
) -> list[tuple[tuple[str, str, str], str]]:
    """``(key, message)`` for every hand-written group of kinds in one module.

    ``key`` is ``(label, owner, members)`` in :data:`NOT_A_ROLE_QUESTION`'s
    shape.
    """
    tree = ast.parse(source)
    owner = _owner_names(tree)
    values = all_known_entrypoint_kinds()
    out: list[tuple[tuple[str, str, str], str]] = []
    for node in ast.walk(tree):
        members = _kind_members(node, values)
        if members is None:
            continue
        where = owner.get(id(node), "<module>")
        key = (label, where, ",".join(sorted(members)))
        out.append((key, f"{label}:{getattr(node, 'lineno', 0)}: hand-written kind "
                         f"set {sorted(members)} in {where} -- ask entrypoint_kinds for "
                         "a role (kinds_with_role) instead"))
    return out


def _python_files(repo_root: Path) -> Iterable[Path]:
    for base in sorted(p for root in DRIFT_SEARCH_ROOTS for p in repo_root.glob(root)):
        for path in sorted(base.rglob("*.py")):
            rel = path.relative_to(repo_root).as_posix()
            if "/tests/" in f"/{rel}" or rel == _THIS_MODULE:
                continue
            yield path
        for path in sorted(base.glob("*")):
            # Extensionless scripts (scripts/check-*) are Python too.
            if path.is_file() and path.suffix == "" and path.read_bytes()[:40].startswith(
                    b"#!/usr/bin/env python"):
                yield path


def find_kind_set_drift(repo_root: Path) -> list[str]:
    """Every hand-written group of kinds outside this module (empty = clean).

    The watcher for audit 0027's two keep-with-a-trigger verdicts: a reader
    that branches on ``main_guard`` without ``main_function``, or on a
    mechanism-named kind (``connectivity_based``, ``script_module``,
    ``shell_script``, ``html_entry``) alone, can only do it with a group of
    kinds of its own, and that group is reported here unless
    :data:`NOT_A_ROLE_QUESTION` names it.
    """
    out: list[str] = []
    for path in _python_files(repo_root):
        rel = path.relative_to(repo_root).as_posix()
        try:
            source = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:  # pragma: no cover - defensive: a binary under scripts/
            continue
        try:
            found = find_kind_set_drift_in_source(source, rel)
        except SyntaxError:  # pragma: no cover - defensive: not Python after all
            continue
        out.extend(msg for key, msg in found if key not in NOT_A_ROLE_QUESTION)
    return out


def unused_not_a_role_question_keys(repo_root: Path) -> list[tuple[str, str, str]]:
    """Allow-list keys that no longer match a site (the list only shrinks)."""
    live: set[tuple[str, str, str]] = set()
    for rel, _where, _members in NOT_A_ROLE_QUESTION:
        source = (repo_root / rel).read_text(encoding="utf-8")
        live.update(key for key, _msg in find_kind_set_drift_in_source(source, rel))
    return sorted(k for k in NOT_A_ROLE_QUESTION if k not in live)


