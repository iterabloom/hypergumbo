"""Canonical registry of entrypoint kinds: the entrypoint-kind axis (ADR-0063).

THE AXIOM. An entrypoint's kind names what the entry IS (ADR-0027's rule for
``Symbol.kind``, carried over by audit 0027); the framework that registered it
and the mechanism that found it go in ``meta`` (``evidence_type`` names the
inference pathway only, ADR-0028). Every kind has exactly one ROLE: what starts
or dispatches the code at that entry. A reader that treats a group of kinds
alike asks for a role, never for a list of kinds.

WHY THIS MODULE EXISTS. Until it did, five readers each held a hand-written
set of kinds, and the sets disagreed (audit 0027, "Five hand-written sets over
one enum"): ``electron_main`` was a program start to the sketch and to nobody
else; a manifest-declared executable ranked first among ties but got no 2x
boost in ``slice --entry auto``; nine kinds fell through every sketch group to
"Other"; and the sets still held 24 kinds nothing produced, the ADR-0023
silent-drift shape. Readers branching on hand-written groups of values is
ADR-0024's condition for a full axis, so the vocabulary moved here and gained
the template's four artifacts:

- this registry (:data:`ENTRYPOINT_KINDS`, :data:`ENTRYPOINT_ROLES`, the
  accessors :func:`entrypoint_kinds_on_axis` / :func:`kinds_with_role` /
  :func:`role_of`);
- the by-axis view: ``docs/concept-axes.md``, generated by
  ``scripts/generate-concept-axes`` from these specs;
- the drift check :func:`find_kind_set_drift` (run by
  ``scripts/check-symbol-kind-drift``, the pre-commit step for the sibling
  kind axis, and by ``tests/test_entrypoint_kinds.py``);
- the property test ``tests/test_entrypoint_kinds.py``.

``EntrypointKind`` itself lives here, so the enum and its roles are one
source; ``hypergumbo_core.entrypoints`` re-exports it.

THE READERS AND THE ROLE QUERY EACH ONE MAKES (each set is computed, never
written out):

- the tie order among entries of equal ``rank_score``
  (:func:`kind_tie_rank`): the package's declared executable, then the
  rest of the program-start role, then the rest (ADR-0039 ruling 3);
- ``slice --entry auto``'s 2x ``kind_boost`` and the Go module-binary pick:
  the program-start role (``entrypoints.PROGRAM_START_KINDS``);
- ``request_ingress``, verify-claims' unseeded-ingress withhold and taint's
  parameter seeds: the request-ingress role
  (``entrypoints.REQUEST_INGRESS_KINDS``);
- the sketch's Entry Points groups: one group per role heading
  (:func:`role_heading`), the test role left to the Tests section;
- the INV-hosuh main dedup: the program-start role;
- the library-export demotion: the roles in :data:`APPLICATION_ROLES`.

Readers that compare ONE kind (the build-wrapper demotion on
``shell_script``, the Go ``cmd/`` penalty on ``main_function``, the
connectivity-boost skips, the route-label dedup's label scheme, taint's
per-kind parameter contracts) ask about that kind's own behaviour, not about
a group, and stay as they are; :data:`NOT_A_ROLE_QUESTION` lists the
multi-kind collections that are not role questions, with the reason for each.

RULINGS. The owner ruled on 2026-11-21 (audit 0027, recorded on WI-holud):
program start is the package's declared executable, the convention main
(``main_function``), ``main_guard`` and ``electron_main``, and nothing else;
``shell_script`` and ``script_module`` stay fallback; ``android_application``
and the Verilog top module are hosted application (the top module is filed
under ``main_function`` until WI-fasij moves it). Each spec records whether
its role was ruled or is proposed here; ``go_handler`` is unruled (WI-hamiz)
and keeps the role its behaviour implies.

THE ROLE OUTSIDE THE AUDIT'S LIST. The audit named eight roles. A framework
subcommand (``cli_command``: click, cobra, oclif, a C ``cmd_<name>``) fits
none of them: it is not a program start (the ruled list is closed), it
receives no request (``REQUEST_INGRESS_KINDS`` excludes a CLI on purpose:
argv is not a request a framework hands over), and it is not reflective or
scheduled. :data:`ROLE_COMMAND` is a ninth role, proposed, for it.
"""

