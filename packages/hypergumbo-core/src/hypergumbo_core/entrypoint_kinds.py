#: Single-kind branches on a kind kept under a trigger (audit 0027: main_guard
#: against main_function; the four mechanism-named kinds), keyed by
#: (repo-relative path, enclosing function, kind member name), each with why
#: it is the kind's own behaviour and not the leak the trigger watches for.
#: A branch on one of these kinds that is not listed fails
#: ``tests/test_entrypoint_kinds.py``, which is the trigger firing: decide
#: then whether the kind still deserves to be kept beside its sibling.
KNOWN_WATCHED_READS: Final[dict[tuple[str, str, str], str]] = {
    ("packages/hypergumbo-core/src/hypergumbo_core/entrypoints.py",
     "detect_entrypoint_candidates", "SHELL_SCRIPT"): (
        "WI-batit: a checked-in mvnw / gradlew wrapper is a shell script by "
        "construction; the demotion is about that file, whatever the role"),
    ("packages/hypergumbo-core/src/hypergumbo_core/entrypoints.py",
     "detect_entrypoint_candidates", "CONNECTIVITY_BASED"): (
        "the connectivity boost skips an entry chosen FOR its connectivity, "
        "which would count the same out-degree twice"),
}


def kept_under_trigger() -> frozenset[EntrypointKind]:
    """The kinds audit 0027 kept under a trigger (the watched kinds)."""
    return frozenset(s.kind for s in ENTRYPOINT_KINDS
                     if s.verdict == VERDICT_KEPT_UNDER_TRIGGER)


def _reads_an_entry_kind(node: ast.expr) -> bool:
    """``<x>.kind``: the operand an entry-kind branch compares."""
    return isinstance(node, ast.Attribute) and node.attr == "kind"


def find_watched_kind_reads_in_source(
    source: str, label: str, watched: frozenset[str],
) -> list[tuple[str, str, str]]:
    """``(label, owner, member)`` for every ``<x>.kind == / != / is
    EntrypointKind.<member>`` comparison on a watched member."""
    tree = ast.parse(source)
    owner = _owner_names(tree)
    out: list[tuple[str, str, str]] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Compare):
            continue
        operands = [node.left, *node.comparators]
        if not any(_reads_an_entry_kind(o) for o in operands):
            continue
        for o in operands:
            member = _is_kind_attr(o)
            if member in watched:
                out.append((label, owner.get(id(node), "<module>"), member))
    return out


def find_watched_kind_reads(repo_root: Path) -> list[tuple[str, str, str]]:
    """Every single-kind branch on a kept-under-trigger kind outside this module."""
    watched = frozenset(k.name for k in kept_under_trigger())
    out: list[tuple[str, str, str]] = []
    for path in _python_files(repo_root):
        rel = path.relative_to(repo_root).as_posix()
        try:
            out.extend(find_watched_kind_reads_in_source(
                path.read_text(encoding="utf-8"), rel, watched))
        except (SyntaxError, UnicodeDecodeError):  # pragma: no cover - defensive
            continue
    return sorted(set(out))
