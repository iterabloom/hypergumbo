def all_known_entrypoint_kinds() -> frozenset[str]:
    """Every entrypoint-kind value (WI-pupiz; the ``_known_axes`` resolver).

    The single source of the schema ``Entrypoint.kind`` enumeration
    (``generate-schema``). Distinct from the ``entrypoint_meta``
    ``evidence_type`` axis (WI-rukam): ``kind`` names WHAT the entrypoint is,
    ``evidence_type`` HOW it was detected. A kind that detection does not
    reach on a given corpus (``cli_command`` for argparse CLIs, WI-lubap) is
    still a known kind.
    """
    return frozenset(k.value for k in EntrypointKind)


def entrypoint_kinds_on_axis(role: str) -> tuple[EntrypointKindSpec, ...]:
    """The specs of every kind whose role is *role* (ADR-0024 accessor shape)."""
    if role not in _ROLE_BY_NAME:
        raise ValueError(f"unknown entrypoint role {role!r}")
    return tuple(s for s in ENTRYPOINT_KINDS if s.role == role)


def kinds_with_role(*roles: str) -> frozenset[EntrypointKind]:
    """The kinds whose role is one of *roles*: how a reader builds its set."""
    return frozenset(s.kind for r in roles for s in entrypoint_kinds_on_axis(r))


def role_of(kind: EntrypointKind) -> str:
    """The role of *kind*."""
    return _SPEC_BY_KIND[kind].role


def role_heading(role: str) -> Optional[str]:
    """The sketch's Entry Points heading for *role* (``None``: not shown there)."""
    return _ROLE_BY_NAME[role].heading


def kind_tie_rank(kind: EntrypointKind) -> int:
    """The first key among entries of equal ``rank_score``: 0, 1 or 2.

    0. the package's declared executable (``package_executable``);
    1. any other program start;
    2. every other role.

    ADR-0039 ruling 3 as amended 2026-11-19: among ties, a manifest script,
    then a main / main guard, then the rest. Before ``package_executable``
    existed, rank 0 read ``meta.evidence_type == "manifest_declared"``,
    because the manifest's executables shared ``cli_command`` with framework
    subcommands; ADR-0028 says that field names the inference pathway, so
    reading it as a category was the leak audit 0027 documented.
    """
    if kind is EntrypointKind.PACKAGE_EXECUTABLE:
        return 0
    return 1 if role_of(kind) == ROLE_PROGRAM_START else 2


