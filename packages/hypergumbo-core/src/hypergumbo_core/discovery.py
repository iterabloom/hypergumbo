"""File discovery with exclude patterns, locale handling, and extension disambiguation.

Provides shared utilities for finding source files across the repository while
respecting exclude patterns. Also provides:

- **Locale-aware doc filtering:** ``detect_locale_dirs()`` identifies translated
  documentation directories (GitLab-style ``doc-locale/<lang>/`` and FastAPI-style
  ``docs/<lang>/``). By default, translated docs are excluded to avoid processing
  duplicate content. The ``--locale`` CLI flag swaps to a specific locale instead.
  ``set_locale_excludes()`` / ``get_locale_excludes()`` provide a global hook
  (like ``set_max_file_bytes``) that ``find_files`` checks.

- **Ambiguous extension disambiguation:**

  - ``.m`` files: shared by Objective-C, MATLAB, and Wolfram.
    ``classify_dot_m_file`` reads file content and uses syntactic heuristics.
  - ``.d`` files: shared by D programming language and GCC Makefile dependency
    files (generated by ``gcc -MMD``). ``classify_dot_d_file`` distinguishes
    D source from dependency files by checking for D keywords vs make rules.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from fnmatch import fnmatch
from pathlib import Path
from typing import Callable, Iterator

# Global file size limit. Set via set_max_file_bytes() before running
# analyzers; find_files() reads this when no explicit max_file_bytes
# is passed. Reset to None after use.
_global_max_file_bytes: int | None = None

# Global callback for skipped files. Set via set_global_on_file_skipped()
# before running analyzers; find_files() uses this when no explicit
# on_file_skipped callback is provided. This allows run_all_analyzers()
# to collect truncated file info without modifying any analyzer signatures.
_global_on_file_skipped: Callable[[Path, int, str], None] | None = None


def set_max_file_bytes(limit: int | None) -> None:
    """Set the global max file bytes limit for find_files().

    Called by the CLI before running analyzers so that all callers of
    find_files() respect the limit without needing individual changes.
    """
    global _global_max_file_bytes
    _global_max_file_bytes = limit


def set_global_on_file_skipped(
    callback: Callable[[Path, int, str], None] | None,
) -> None:
    """Set a global callback for files skipped due to size limits.

    Called by run_all_analyzers() to wire skipped-file tracking into
    the Limits object without modifying individual analyzer signatures.
    When find_files() skips a file and no explicit on_file_skipped
    callback is provided, it falls back to this global callback.
    """
    global _global_on_file_skipped
    _global_on_file_skipped = callback


